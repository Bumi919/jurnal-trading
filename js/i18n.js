/* =========================================================
   i18n.js - Dukungan bahasa (Indonesia + English)
   Pola: t('teks Indonesia') -- bila bahasa aktif English,
   kembalikan padanan dari kamus STR.en; bila tidak ada,
   kembalikan teks aslinya (aman, tidak pernah kosong).
   Ganti bahasa = tulis localStorage lalu muat ulang halaman.
   ========================================================= */

var LANGS = { id: 'Indonesia', en: 'English' };
var LANG_KEY = 'jt_lang';

function getLang() {
  var l = null;
  try { l = localStorage.getItem(LANG_KEY); } catch (e) { l = null; }
  return LANGS[l] ? l : 'id';
}

function setLang(l) {
  if (!LANGS[l]) return;
  try { localStorage.setItem(LANG_KEY, l); } catch (e) { /* abaikan */ }
  location.reload();
}

function t(s, vars) {
  var lang = getLang();
  var out = s;
  if (lang !== 'id' && STR.en && STR.en[s]) out = STR.en[s];
  if (vars) {
    out = out.replace(/\{(\w+)\}/g, function (m, k) {
      return vars[k] == null ? m : vars[k];
    });
  }
  return out;
}

function numLocale() {
  return getLang() === 'en' ? 'en-US' : 'id-ID';
}

function monthNames() {
  if (getLang() === 'en') {
    return ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
      'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  }
  return ['Jan', 'Feb', 'Mar', 'Apr', 'Mei', 'Jun',
    'Jul', 'Agu', 'Sep', 'Okt', 'Nov', 'Des'];
}

function weekdayNames() {
  if (getLang() === 'en') {
    return ['Sunday', 'Monday', 'Tuesday', 'Wednesday',
      'Thursday', 'Friday', 'Saturday'];
  }
  return ['Minggu', 'Senin', 'Selasa', 'Rabu', 'Kamis', 'Jumat', 'Sabtu'];
}

function shortDowNames() {
  if (getLang() === 'en') {
    return ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];
  }
  return ['Sen', 'Sel', 'Rab', 'Kam', 'Jum', 'Sab', 'Min'];
}

